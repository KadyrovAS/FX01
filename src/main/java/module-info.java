/**
 * Модуль приложения "Визуальный конструктор".
 * <p>
 * Использует JavaFX для десктопного интерфейса и JFreeChart для отображения графиков.
 * </p>
 *
 * @module com.myapp.dashboard
 */
module com.myapp.dashboard {
    // ================================================================
    // ТРЕБУЕМЫЕ МОДУЛИ
    // ================================================================

    /** JavaFX Controls — основные элементы управления */
    requires javafx.controls;

    /** JavaFX FXML — разметка интерфейса (опционально) */
    requires javafx.fxml;

    /** JFreeChart — библиотека для графиков */
    requires org.jfree.jfreechart;

    // ================================================================
    // ОТКРЫТЫЕ ПАКЕТЫ ДЛЯ РЕФЛЕКСИИ
    // ================================================================

    /** Открываем контроллеры для JavaFX FXML */
    opens org.controller to javafx.fxml;

    /** Открываем модели для JavaFX (свойства) */
    opens org.model to javafx.base;

    /** Открываем сервисы для JavaFX */
    opens org.service to javafx.base;

    /** Открываем компоненты для JavaFX */
    opens org.components to javafx.base;

    /** Открываем корневой пакет для графики */
    opens org to javafx.graphics;

    // ================================================================
    // ЭКСПОРТИРУЕМЫЕ ПАКЕТЫ
    // ================================================================

    /** Экспортируем корневой пакет для внешнего использования */
    exports org;

    /** Экспортируем контроллеры */
    exports org.controller;

    /** Экспортируем модели данных */
    exports org.model;

    /** Экспортируем сервисы */
    exports org.service;

    /** Экспортируем компоненты */
    exports org.components;
}